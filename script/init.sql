-- ============================================================
-- SCRIPT DDL - Centros de Evaluación de Manejo
-- Basado en Práctica 1 y datos de prueba para Proyecto 2
-- ============================================================

-- ------------------------------------------------------------
-- 1. TABLAS CATÁLOGO
-- ------------------------------------------------------------

-- DEPARTAMENTO
CREATE TABLE DEPARTAMENTO (
    id_departamento NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR2(2) NOT NULL UNIQUE,
    nombre VARCHAR2(100) NOT NULL
);

-- MUNICIPIO
CREATE TABLE MUNICIPIO (
    id_municipio NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR2(3) NOT NULL,
    nombre VARCHAR2(100) NOT NULL,
    id_departamento NUMBER NOT NULL,
    CONSTRAINT fk_municipio_departamento FOREIGN KEY (id_departamento) REFERENCES DEPARTAMENTO(id_departamento),
    CONSTRAINT uk_municipio UNIQUE (id_departamento, codigo)
);

-- CENTRO (de evaluación)
CREATE TABLE CENTRO (
    id_centro NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR2(150) NOT NULL,
    direccion VARCHAR2(255)
);

-- ESCUELA (de automovilismo)
CREATE TABLE ESCUELA (
    id_escuela NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR2(150) NOT NULL,
    direccion VARCHAR2(255),
    acuerdo VARCHAR2(50) NOT NULL UNIQUE   -- número de autorización
);

-- UBICACION (relación muchos a muchos entre ESCUELA y CENTRO)
CREATE TABLE UBICACION (
    id_ubicacion NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_escuela NUMBER NOT NULL,
    id_centro NUMBER NOT NULL,
    CONSTRAINT fk_ubicacion_escuela FOREIGN KEY (id_escuela) REFERENCES ESCUELA(id_escuela),
    CONSTRAINT fk_ubicacion_centro FOREIGN KEY (id_centro) REFERENCES CENTRO(id_centro),
    CONSTRAINT uk_ubicacion UNIQUE (id_escuela, id_centro)
);

-- TIPO_LICENCIA (M, P, B, A, E)
CREATE TABLE TIPO_LICENCIA (
    id_tipo_licencia NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo CHAR(1) NOT NULL UNIQUE,
    descripcion VARCHAR2(50) NOT NULL
);

-- TIPO_TRAMITE (primera licencia, cambio de tipo)
CREATE TABLE TIPO_TRAMITE (
    id_tipo_tramite NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR2(50) NOT NULL UNIQUE
);

-- USUARIO (personal que atiende en el centro)
CREATE TABLE USUARIO (
    id_usuario NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    identificacion VARCHAR2(20) NOT NULL UNIQUE,
    nombre_completo VARCHAR2(150) NOT NULL,
    rol VARCHAR2(50)
);

-- INSTRUCTOR (para evaluación práctica)
CREATE TABLE INSTRUCTOR (
    id_instructor NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    identificacion VARCHAR2(20) NOT NULL UNIQUE,
    nombre_completo VARCHAR2(150) NOT NULL,
    especialidad VARCHAR2(100)
);

-- ------------------------------------------------------------
-- 2. TABLAS DE NEGOCIO
-- ------------------------------------------------------------

-- PERSONA (aspirante)
CREATE TABLE PERSONA (
    id_persona NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    identificacion VARCHAR2(20) NOT NULL UNIQUE,
    nombre_completo VARCHAR2(200) NOT NULL,
    direccion VARCHAR2(255),
    telefono VARCHAR2(20),
    fotografia BLOB,
    genero CHAR(1) CHECK (genero IN ('M', 'F', 'O')),
    fecha_nacimiento DATE,
    id_departamento NUMBER NOT NULL,
    id_municipio NUMBER NOT NULL,
    CONSTRAINT fk_persona_departamento FOREIGN KEY (id_departamento) REFERENCES DEPARTAMENTO(id_departamento),
    CONSTRAINT fk_persona_municipio FOREIGN KEY (id_municipio) REFERENCES MUNICIPIO(id_municipio)
);

-- REGISTRO (inscripción de una persona en una escuela y centro)
CREATE TABLE REGISTRO (
    id_registro NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha_registro DATE NOT NULL,
    id_persona NUMBER NOT NULL,
    id_ubicacion NUMBER NOT NULL,
    id_tipo_tramite NUMBER NOT NULL,
    id_tipo_licencia NUMBER NOT NULL,
    id_usuario_atendio NUMBER NOT NULL,
    CONSTRAINT fk_registro_persona FOREIGN KEY (id_persona) REFERENCES PERSONA(id_persona),
    CONSTRAINT fk_registro_ubicacion FOREIGN KEY (id_ubicacion) REFERENCES UBICACION(id_ubicacion),
    CONSTRAINT fk_registro_tipo_tramite FOREIGN KEY (id_tipo_tramite) REFERENCES TIPO_TRAMITE(id_tipo_tramite),
    CONSTRAINT fk_registro_tipo_licencia FOREIGN KEY (id_tipo_licencia) REFERENCES TIPO_LICENCIA(id_tipo_licencia),
    CONSTRAINT fk_registro_usuario FOREIGN KEY (id_usuario_atendio) REFERENCES USUARIO(id_usuario)
);

-- CORRELATIVO DIARIO (control de número de examen por día)
CREATE TABLE CORRELATIVO (
    id_correlativo NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha DATE NOT NULL,
    no_examen NUMBER NOT NULL,
    CONSTRAINT uk_correlativo_diario UNIQUE (fecha, no_examen)
);

-- EXAMEN (teórico + práctico)
CREATE TABLE EXAMEN (
    id_examen NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_registro NUMBER NOT NULL,
    id_correlativo NUMBER NOT NULL,
    fecha_hora TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    resultado_teorico NUMBER(5,2),           -- puntaje total teórico (máx 100)
    resultado_practico NUMBER(5,2),          -- puntaje total práctico (máx según sumatoria de preguntas)
    id_instructor NUMBER,
    CONSTRAINT fk_examen_registro FOREIGN KEY (id_registro) REFERENCES REGISTRO(id_registro),
    CONSTRAINT fk_examen_correlativo FOREIGN KEY (id_correlativo) REFERENCES CORRELATIVO(id_correlativo),
    CONSTRAINT fk_examen_instructor FOREIGN KEY (id_instructor) REFERENCES INSTRUCTOR(id_instructor)
);

-- ------------------------------------------------------------
-- 3. PREGUNTAS Y RESPUESTAS
-- ------------------------------------------------------------

-- PREGUNTA TEÓRICA (con 4 opciones fijas)
CREATE TABLE PREGUNTA_TEORICA (
    id_pregunta_teorica NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    texto VARCHAR2(500) NOT NULL,
    imagen VARCHAR2(255),   -- ruta o URL
    respuesta_a VARCHAR2(300) NOT NULL,
    respuesta_b VARCHAR2(300) NOT NULL,
    respuesta_c VARCHAR2(300) NOT NULL,
    respuesta_d VARCHAR2(300) NOT NULL,
    opcion_correcta CHAR(1) CHECK (opcion_correcta IN ('A','B','C','D')) NOT NULL
);

-- RESPUESTA del usuario a una pregunta teórica
CREATE TABLE RESPUESTA_TEORICA (
    id_respuesta_teorica NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_examen NUMBER NOT NULL,
    id_pregunta_teorica NUMBER NOT NULL,
    respuesta_seleccionada CHAR(1) CHECK (respuesta_seleccionada IN ('A','B','C','D')) NOT NULL,
    es_correcta NUMBER(1) DEFAULT 0 CHECK (es_correcta IN (0,1)),
    puntos_obtenidos NUMBER(3,0) DEFAULT 0,
    CONSTRAINT fk_rt_examen FOREIGN KEY (id_examen) REFERENCES EXAMEN(id_examen),
    CONSTRAINT fk_rt_pregunta FOREIGN KEY (id_pregunta_teorica) REFERENCES PREGUNTA_TEORICA(id_pregunta_teorica),
    CONSTRAINT uk_rt_examen_pregunta UNIQUE (id_examen, id_pregunta_teorica)
);

-- PREGUNTA PRÁCTICA
CREATE TABLE PREGUNTA_PRACTICA (
    id_pregunta_practica NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    texto VARCHAR2(500) NOT NULL,
    punteo_maximo NUMBER(5,2) NOT NULL   -- valor de la pregunta (ej: 10, 20, etc.)
);

-- RESPUESTA a pregunta práctica (nota asignada por instructor)
CREATE TABLE RESPUESTA_PRACTICA (
    id_respuesta_practica NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_examen NUMBER NOT NULL,
    id_pregunta_practica NUMBER NOT NULL,
    nota_obtenida NUMBER(5,2) NOT NULL,
    comentario_instructor VARCHAR2(400),
    CONSTRAINT fk_rp_examen FOREIGN KEY (id_examen) REFERENCES EXAMEN(id_examen),
    CONSTRAINT fk_rp_pregunta FOREIGN KEY (id_pregunta_practica) REFERENCES PREGUNTA_PRACTICA(id_pregunta_practica),
    CONSTRAINT uk_rp_examen_pregunta UNIQUE (id_examen, id_pregunta_practica)
);

